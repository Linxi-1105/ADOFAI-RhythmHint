// dotnet run tools/ExportReviewDemo.cs -- tools/review-editor/demo.json
// 由 C# NotePlanner 生成；仅为审核操作示例，不是任何真实关卡。
using RhythmHint.Core;

if (args.Length != 1)
{
    Console.Error.WriteLine("用法：dotnet run tools/ExportReviewDemo.cs -- <输出.json>");
    return 2;
}

var options = new FingeringOptions();
var demo = DemoChart.Build(160);
var hits = DemoChart.Repeat(demo, 3).ToList();
// Explicit angle chains demonstrate 3K/4K and preserve individual holds.
var nextTile = hits.Max(hit => hit.TileIndex) + 1;
var start = hits[^1].Time + 1;
foreach (var count in new[] { 3, 4 })
{
    for (var i = 0; i < count; i++) hits.Add(new TileHit(nextTile++, start + i * .02, (i + 1) * .125, i == 0 ? 180 : 15));
    start += 1;
}
var notes = NotePlanner.Plan(hits, options);
var json = ReviewChart.Export("审核演示 · 慢速、交替、轮指、多押与长按", "demo", notes, options,
    exportedAt: new DateTimeOffset(2026, 11, 17, 0, 0, 0, TimeSpan.Zero), sourceHits: hits);
var output = Path.GetFullPath(args[0]);
Directory.CreateDirectory(Path.GetDirectoryName(output)!);
File.WriteAllText(output, json, new System.Text.UTF8Encoding(false));
File.WriteAllText(Path.ChangeExtension(output, ".js"),
    "// Generated by tools/ExportReviewDemo.cs; synthetic C# baseline.\nwindow.RHYTHMHINT_DEMO = " + json.TrimEnd() + ";\n",
    new System.Text.UTF8Encoding(false));
Console.WriteLine($"已导出 {notes.Count} 个演示提示到 {output}");
return 0;
