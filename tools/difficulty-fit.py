"""拟合难度估算模型，生成 src/RhythmHint.Core/DifficultyModel.g.cs。

特征由 C# 的 Core 算（和游戏里同一份代码），这里只拟合：
    dotnet run tools/Difficulty.cs -- export <校准文件夹> features.csv
    python tools/difficulty-fit.py features.csv
依赖 numpy 和 scikit-learn（只在开发时用，Mod 不需要）。
模型：梯度提升树（100 棵、深 3、学习率 0.1），目标是 TUF 档位 1–60；只用离线时间算得准、至少 20 次按键的关卡。
输出 10 折交叉验证的误差（换三种随机划分取平均），再用全部数据拟合并写出 C# 文件。
"""
import csv
import os
import re
import sys

import numpy as np
from sklearn.ensemble import GradientBoostingRegressor
from sklearn.model_selection import KFold

PARAMS = dict(n_estimators=100, max_depth=3, learning_rate=0.1, subsample=0.8)
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUTPUT = os.path.join(ROOT, "src", "RhythmHint.Core", "DifficultyModel.g.cs")


def core_feature_names():
    text = open(os.path.join(ROOT, "src", "RhythmHint.Core", "DifficultyEstimator.cs"), encoding="utf-8").read()
    block = re.search(r"Names =\s*\{(.*?)\};", text, re.S).group(1)
    return re.findall(r'"([^"]+)"', block)


def load(path, names):
    rows = list(csv.DictReader(open(path, encoding="utf-8")))
    missing = [n for n in names if n not in rows[0]]
    if missing:
        sys.exit(f"features.csv 缺少特征 {missing}：先用最新的 Core 重新 export")
    rows = [r for r in rows if int(r["actual"]) > 0 and r["exact"] == "1" and int(r["hits"]) >= 20]
    X = np.array([[float(r[n]) for n in names] for r in rows])
    y = np.array([float(r["actual"]) for r in rows])
    return X, y


def cross_validate(X, y):
    errors = []
    for seed in range(3):
        pred = np.zeros(len(y))
        for train, test in KFold(10, shuffle=True, random_state=seed).split(X):
            model = GradientBoostingRegressor(random_state=seed, **PARAMS).fit(X[train], y[train])
            pred[test] = model.predict(X[test])
        errors.append(np.abs(np.clip(np.round(pred), 1, 60) - y))
    e = np.mean(errors, axis=0)
    print(f"{len(y)} 关，10 折交叉验证：平均差 {e.mean():.2f} 档；"
          + "，".join(f"≤{k} 档 {np.mean(e <= k) * 100:.0f}%" for k in (1, 2, 3, 5, 8)))
    for g, name in enumerate("PGU"):
        m = (y > g * 20) & (y <= g * 20 + 20)
        if m.any():
            print(f"  {name}: {m.sum()} 关，平均差 {e[m].mean():.2f}")


def write_model(model, names, y):
    nodes = []  # (特征, 阈值, 左, 右, 值)：特征为 -1 是叶子
    roots = []
    for est in model.estimators_[:, 0]:
        tree = est.tree_
        base = len(nodes)
        roots.append(base)
        for i in range(tree.node_count):
            leaf = tree.children_left[i] == -1
            nodes.append((
                -1 if leaf else int(tree.feature[i]),
                0.0 if leaf else float(tree.threshold[i]),
                -1 if leaf else base + int(tree.children_left[i]),
                -1 if leaf else base + int(tree.children_right[i]),
                float(tree.value[i][0][0]) if leaf else 0.0,
            ))

    def arr(values, fmt):
        out, line = [], "        "
        for v in values:
            s = fmt(v) + ", "
            if len(line) + len(s) > 120:
                out.append(line.rstrip())
                line = "        "
            line += s
        out.append(line.rstrip())
        return "\n".join(out)

    init = float(model.init_.constant_[0][0])
    text = f"""// <auto-generated>
// 由 tools/difficulty-fit.py 生成，不要手改：改特征或重新校准后重新运行它。
// 梯度提升树 {len(roots)} 棵（深 {PARAMS['max_depth']}、学习率 {PARAMS['learning_rate']}），{len(y)} 张 TUF 已评级谱面（档位 {int(y.min())}–{int(y.max())}）。
// 特征顺序：{", ".join(names)}
// </auto-generated>

namespace RhythmHint.Core;

/// <summary>难度估算的模型：特征 → 档位分数。和 scikit-learn 一样，特征先转成 float 再和阈值比较。</summary>
internal static class DifficultyModel
{{
    public const int FeatureCount = {len(names)};
    private const double Init = {init!r};
    private const double LearningRate = {PARAMS['learning_rate']!r};

    private static readonly int[] Roots =
    {{
{arr(roots, str)}
    }};

    private static readonly int[] Feature =
    {{
{arr([n[0] for n in nodes], str)}
    }};

    private static readonly double[] Threshold =
    {{
{arr([n[1] for n in nodes], lambda v: repr(v))}
    }};

    private static readonly int[] Left =
    {{
{arr([n[2] for n in nodes], str)}
    }};

    private static readonly int[] Right =
    {{
{arr([n[3] for n in nodes], str)}
    }};

    private static readonly double[] Value =
    {{
{arr([n[4] for n in nodes], lambda v: repr(v))}
    }};

    public static double Predict(double[] features)
    {{
        var score = Init;
        foreach (var root in Roots)
        {{
            var i = root;
            while (Feature[i] >= 0)
            {{
                i = (float)features[Feature[i]] <= Threshold[i] ? Left[i] : Right[i];
            }}

            score += LearningRate * Value[i];
        }}

        return score;
    }}
}}
"""
    with open(OUTPUT, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
    print(f"已写 {OUTPUT}（{len(nodes)} 个节点）")


def main():
    if len(sys.argv) < 2:
        sys.exit("用法：python tools/difficulty-fit.py features.csv")
    names = core_feature_names()
    X, y = load(sys.argv[1], names)
    cross_validate(X, y)
    model = GradientBoostingRegressor(random_state=0, **PARAMS).fit(X, y)
    train = np.abs(np.clip(np.round(model.predict(X)), 1, 60) - y)
    print(f"全部数据拟合（训练集，偏乐观）：平均差 {train.mean():.2f} 档")
    write_model(model, names, y)


if __name__ == "__main__":
    main()
